fn generic_pre_anchored_heading(
    g: *Generator,
    node: *anyopaque,
) Generator.GenError!?@Vector(2, usize) {
    const realnode: *Node.L0 = @ptrCast(@alignCast(node));
    const span = realnode.span;

    if (span == null) crash(error.NullSpan);

    const anchorbuf: []u8 = g.alloc.alloc(u8, span.?[1] - span.?[0]) catch crash(error.OOM);
    defer g.alloc.free(anchorbuf);
    @memcpy(anchorbuf, g.textin[span.?[0]..span.?[1]]);

    for (anchorbuf) |*c| {
        if (!std.ascii.isAlphanumeric(c.*)) {
            c.* = '-';
        } else if (std.ascii.isUpper(c.*)) {
            c.* = std.ascii.toLower(c.*);
        }
    }

    switch (realnode.kind) {
        .heading2 => g.print("<h2 "),
        .heading3 => g.print("<h3 "),
        .heading4 => g.print("<h4 "),
        .heading5 => g.print("<h5 "),
        .heading6 => g.print("<h6 "),
        else => unreachable,
    }

    g.print("id=\"");
    g.print(anchorbuf);
    g.print("\"><a href=\"#");
    g.print(anchorbuf);
    g.print("\" class=\"heading-link\">");
    if (g.attributor.get_newest(.heading_icon)) |l0_icon_node| {
        g.print("<span class=\"chain-icon\">");
        g.print_span(l0_icon_node.span.?[0], l0_icon_node.span.?[1]);
        g.print("</span>");
    }

    return span;
}

fn pre_command_img(g: *Generator, node: *anyopaque) Generator.GenError!?@Vector(2, usize) {
    const realnode: *Node.L0 = @ptrCast(@alignCast(node));
    const span = realnode.span;

    if (span == null) crash(error.NullSpan);

    var commas: [2]usize = .{ 0, 0 };
    var postcomma_argstarts: [2]usize = .{ 0, 0 };
    var commac: usize = 0;
    var last_c: usize = 0;
    for (g.textin[span.?[0]..span.?[1]], 0..) |c, i| {
        if (c == ',') {
            if (last_c == '\\') continue;

            for (g.textin[span.?[0] + i + 1 .. span.?[1]], i + 1..) |c2, j| {
                if (c2 != ' ' and c2 != '\t') {
                    postcomma_argstarts[commac] = j;
                    break;
                }
            }

            commas[commac] = i;
            commac += 1;
            if (commac >= 2) break;
        }
        last_c = c;
    }

    if (commac == 0) {
        g.print("<img src=\"");
        g.print_span(span.?[0], span.?[1]);
        g.print("\" alt=\"");
        g.print_span(span.?[0], span.?[1]);
        g.print("\"></figure>");
        return null; // just the link
    }

    if (commac == 1) {
        g.print("<figure><img src=\"");
        g.print_span(span.?[0], span.?[0] + commas[0]);
        g.print("\" alt=\"");
        return @Vector(2, usize){ span.?[0] + postcomma_argstarts[0], span.?[1] };
    }

    if (commac == 2) {
        g.print("<figure><img src=\"");
        g.print_span(span.?[0], span.?[0] + commas[0]);
        g.print("\" style=\"width:");
        g.print_span(span.?[0] + postcomma_argstarts[0], span.?[0] + commas[1]);
        g.print("; height: auto;\" alt=\"");
        g.print_span(span.?[0] + postcomma_argstarts[1], span.?[1]);
        g.print("\"><figcaption>");
        return @Vector(2, usize){ span.?[0] + postcomma_argstarts[1], span.?[1] };
    }

    unreachable;
}

fn post_command_img(g: *Generator, node: *anyopaque) Generator.GenError!void {
    const realnode: *Node.L0 = @ptrCast(@alignCast(node));
    const span = realnode.span;

    if (span == null) crash(error.NullSpan);

    var commas: [2]usize = .{ 0, 0 };
    var postcomma_argstarts: [2]usize = .{ 0, 0 };
    var commac: usize = 0;
    var last_c: usize = 0;
    for (g.textin[span.?[0]..span.?[1]], 0..) |c, i| {
        if (c == ',') {
            if (last_c == '\\') continue;

            for (g.textin[span.?[0] + i + 1 .. span.?[1]], i + 1..) |c2, j| {
                if (c2 != ' ' and c2 != '\t') {
                    postcomma_argstarts[commac] = j;
                    break;
                }
            }

            commas[commac] = i;
            commac += 1;
            if (commac >= 2) break;
        }
        last_c = c;
    }

    if (commac == 1 or commac == 2) {
        g.print("</figcaption></figure>");
    } // else nothing, since we already printed it.
}
